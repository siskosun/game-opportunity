/** Run against pinned Echo Tide production game.js and the new UI-only helper. */
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { readFileSync } from 'node:fs';
const root = resolve(process.argv[2] || '');
assert.ok(root, 'root path required');
const mod = n => import(pathToFileURL(resolve(root, 'src', n)).href);
const core = await mod('game.js');
const { describeVisualHud } = await mod('visual_hud.js');
const { createGame, update, airborneForecast, echoMotionPlan, ECHO, PLAYER } = core;
const tick = (g, input={}) => update(g, input, 1/60);
const checked=[];
let game = createGame({level:1,seed:3,challenge:true,surf:true});
let row = describeVisualHud(game);
assert.equal(row.state,'tutorial');
assert.equal(row.status,'潮印待揭晓');
assert.ok(!row.cue.includes('左岸') && !row.cue.includes('右岸'));
checked.push('hidden route remains hidden');
for(let i=0;i<90&&!game.route.revealed;i++)game=tick(game,{right:true,jump:i<18});
assert.equal(game.route.revealed,true,'real input-only first landing');
assert.equal(game.player.supportId,'echo-1');
for(let i=0;i<15;i++)game=tick(game);
const forecast=airborneForecast(game);
assert.equal(forecast.blocked,false);
assert.ok(echoMotionPlan(game,forecast.target)?.active);
row=describeVisualHud(game);
assert.equal(row.state,'rail');
assert.match(row.cue,/亮轨/);
checked.push('input-only first landing previews actual moving rail');
game=tick(game,{jump:true});
assert.ok(game.flightBridgeId);
for(let i=0;i<24;i++)game=tick(game,{jump:i<18});
row=describeVisualHud(game);
assert.ok(row.state === 'rail' || row.state === 'notice', 'actual moving rail remains visible while airborne');
checked.push('in-flight rail comes from actual physics state');
const blocked=createGame({level:1,seed:7,challenge:true,surf:true});
const width=80;
blocked.echoes=[{id:'echo-1',x:960-width-18,y:402,w:width,h:ECHO.h,phase:'solid',age:0}];
blocked.nextId=2;
blocked.route={revealed:true,side:'right'};
Object.assign(blocked.player,{x:960-PLAYER.w-10,y:402-PLAYER.h,vx:0,vy:0,grounded:true,supportId:'echo-1',facing:1});
assert.equal(airborneForecast(blocked).blocked,true);
row=describeVisualHud(blocked);
assert.equal(row.state,'blocked');
assert.match(row.cue,/空间不足/);
checked.push('synthetic boundary fixture matches blocked forecast');
let dead=createGame({level:1,seed:3,challenge:true,surf:true});
Object.assign(dead.player,{y:560,grounded:false,supportId:null});
dead=tick(dead);
assert.equal(dead.status,'lost');
row=describeVisualHud(dead);
assert.equal(row.state,'lost');
checked.push('terminal lost state has non-deceptive cue');
const helper=readFileSync(resolve(root,'src','visual_hud.js'),'utf8');
assert.ok(!/game\.(player|route|level|status)\s*=|game\.echoes\.push/.test(helper),'UI helper must not assign authoritative game state');
console.log(JSON.stringify({ok:true,checks:checked,pinned_prod_source:'38b9daa1adf78002c8ec5349c269a4ce31959d8f',limit:'fixtures are not human device assessment'},null,2));
